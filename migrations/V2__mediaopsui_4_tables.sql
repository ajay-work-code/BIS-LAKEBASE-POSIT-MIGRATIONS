CREATE SCHEMA IF NOT EXISTS media_internalization;

-- ----------------------------------------------------------------------------
-- 1. app_users
-- ----------------------------------------------------------------------------
CREATE TABLE media_internalization.app_users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(255) NOT NULL,
    password      VARCHAR(255) NOT NULL,
    roles         TEXT,
    role_key      VARCHAR(50),
    PRIMARY KEY (id),
    UNIQUE (username)
);

-- ----------------------------------------------------------------------------
-- 10. media_internalization_file_status
-- ----------------------------------------------------------------------------
CREATE TABLE media_internalization.media_internalization_file_status (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    vendorname           VARCHAR(200) NOT NULL,
    source_path          VARCHAR(2048) NOT NULL,
    status               BOOLEAN,
    processed_data_count INTEGER,
    invalid_data_count   INTEGER,
    error_msg            VARCHAR(2048),
    processed_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    retry_count          INTEGER NOT NULL DEFAULT 0,
    process_end_at       TIMESTAMP,
    uploaded_file_name   VARCHAR(300),
    PRIMARY KEY (id)
);

-- ----------------------------------------------------------------------------
-- 25. rbac_role_permissions
-- ----------------------------------------------------------------------------
CREATE TABLE media_internalization.rbac_role_permissions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    role_key      VARCHAR(50) NOT NULL,
    resource_key  VARCHAR(120) NOT NULL,
    allowed       BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id)
);

-- ----------------------------------------------------------------------------
-- 26. rbac_roles
-- ----------------------------------------------------------------------------
CREATE TABLE media_internalization.rbac_roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    role_key    VARCHAR(50) NOT NULL,
    label       VARCHAR(100) NOT NULL,
    is_system   BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);