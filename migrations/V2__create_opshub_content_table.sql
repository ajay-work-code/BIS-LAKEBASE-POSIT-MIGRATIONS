-- =====================================================================
-- opshub schema: SQL Server (T-SQL) -> Lakebase Postgres (PostgreSQL 16+)
-- Source: SSMS script dated 10/22/2026
-- Run as a single transaction: all objects are created or none are.
-- =====================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS opshub;

-- ---------------------------------------------------------------------
-- roles
-- ---------------------------------------------------------------------
CREATE TABLE opshub.roles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name             VARCHAR(100)  NOT NULL,
    description      VARCHAR(255)  NULL,
    permissions      TEXT          NOT NULL DEFAULT '[]',
    is_system        BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order       INTEGER       NOT NULL DEFAULT 0,
    status           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by       BIGINT        NULL,
    created_by_role  BIGINT        NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_permissions_json CHECK (permissions IS JSON)
);

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE opshub.users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username         VARCHAR(150)  NOT NULL,
    email            VARCHAR(255)  NULL,
    full_name        VARCHAR(200)  NULL,
    job_title        VARCHAR(150)  NULL,
    department       VARCHAR(150)  NULL,
    employee_id      VARCHAR(40)   NULL,
    avatar_url       VARCHAR(500)  NULL,
    avatar_color     VARCHAR(9)    NULL,
    theme_mode       VARCHAR(10)   NOT NULL DEFAULT 'light',
    role_id          BIGINT        NULL,
    last_login_at    TIMESTAMP(6)  NULL,
    deleted_at       TIMESTAMP(6)  NULL,
    status           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by       BIGINT        NULL,
    created_by_role  BIGINT        NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT ck_users_theme CHECK (theme_mode IN ('dark', 'light'))
);

-- ---------------------------------------------------------------------
-- projects
-- ---------------------------------------------------------------------
CREATE TABLE opshub.projects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code                VARCHAR(60)   NOT NULL,
    name                VARCHAR(150)  NOT NULL,
    description         VARCHAR(1000) NULL,
    icon                VARCHAR(80)   NOT NULL DEFAULT 'cubes-stacked',
    favicon_key         VARCHAR(255)  NULL,
    categories          TEXT          NOT NULL DEFAULT '[]',
    categories_enabled  BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order          INTEGER       NOT NULL DEFAULT 0,
    deleted_at          TIMESTAMP(6)  NULL,
    status              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at          TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by          BIGINT        NULL,
    created_by_role     BIGINT        NULL,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT uq_projects_code UNIQUE (code),
    CONSTRAINT ck_projects_categories_json CHECK (categories IS JSON)
);

-- ---------------------------------------------------------------------
-- project_access
-- ---------------------------------------------------------------------
CREATE TABLE opshub.project_access (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id             BIGINT        NOT NULL,
    project_id          BIGINT        NOT NULL,
    state               VARCHAR(20)   NOT NULL DEFAULT 'GRANTED',
    can_view_videos     BOOLEAN       NOT NULL DEFAULT FALSE,
    can_view_runbooks   BOOLEAN       NOT NULL DEFAULT FALSE,
    request_note        VARCHAR(500)  NULL,
    decided_at          TIMESTAMP(6)  NULL,
    decided_by          BIGINT        NULL,
    status              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at          TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by          BIGINT        NULL,
    created_by_role     BIGINT        NULL,
    can_view_handbooks  BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_project_access PRIMARY KEY (id),
    CONSTRAINT uq_project_access UNIQUE (user_id, project_id),
    CONSTRAINT ck_pa_state CHECK (state IN ('DENIED', 'REQUESTED', 'GRANTED'))
);

-- ---------------------------------------------------------------------
-- content
-- ---------------------------------------------------------------------
CREATE TABLE opshub.content (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind               VARCHAR(20)   NOT NULL,
    project_id         BIGINT        NOT NULL,
    category_id        BIGINT        NULL,
    title              VARCHAR(200)  NOT NULL,
    description        TEXT          NULL,
    publish_status     VARCHAR(20)   NOT NULL DEFAULT 'Published',
    version_enabled    BOOLEAN       NOT NULL DEFAULT FALSE,
    version_number     VARCHAR(20)   NULL,
    sort_order         INTEGER       NOT NULL DEFAULT 0,
    storage_key        VARCHAR(500)  NULL,
    thumbnail_key      VARCHAR(500)  NULL,
    original_filename  VARCHAR(255)  NULL,
    file_size          BIGINT        NULL,
    duration_seconds   INTEGER       NULL,
    source_url         VARCHAR(1000) NULL,
    page_count         INTEGER       NULL,
    status             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at         TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by         BIGINT        NULL,
    created_by_role    BIGINT        NULL,
    CONSTRAINT pk_content PRIMARY KEY (id),
    CONSTRAINT ck_content_kind CHECK (kind IN ('HANDBOOK', 'RUNBOOK', 'VIDEO')),
    CONSTRAINT ck_content_publish CHECK (publish_status IN ('Draft', 'Published'))
);

-- ---------------------------------------------------------------------
-- content_versions
-- ---------------------------------------------------------------------
CREATE TABLE opshub.content_versions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    content_id       BIGINT        NOT NULL,
    version_number   VARCHAR(20)   NOT NULL,
    publish_status   VARCHAR(20)   NOT NULL,
    note             VARCHAR(500)  NULL,
    updated_by_id    BIGINT        NULL,
    updated_by_name  VARCHAR(200)  NULL,
    updated_by_role  VARCHAR(100)  NULL,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT pk_content_versions PRIMARY KEY (id)
);

-- ---------------------------------------------------------------------
-- content_index
-- ---------------------------------------------------------------------
CREATE TABLE opshub.content_index (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_key       VARCHAR(80)   NOT NULL,
    content_id       BIGINT        NULL,
    project_id       BIGINT        NULL,
    kind             VARCHAR(20)   NOT NULL,
    title            VARCHAR(200)  NULL,
    content          TEXT          NOT NULL,
    indexed_at       TIMESTAMP(6)  NULL,
    status           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by       BIGINT        NULL,
    created_by_role  BIGINT        NULL,
    CONSTRAINT pk_content_index PRIMARY KEY (id),
    CONSTRAINT uq_ci_source_key UNIQUE (source_key),
    CONSTRAINT ck_ci_content_json CHECK (content IS JSON)
);

-- ---------------------------------------------------------------------
-- content_chunk
-- ---------------------------------------------------------------------
CREATE TABLE opshub.content_chunk (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    document_id      BIGINT           NOT NULL,
    content_id       BIGINT           NULL,
    project_id       BIGINT           NULL,
    kind             VARCHAR(20)      NOT NULL,
    ordinal          INTEGER          NOT NULL DEFAULT 0,
    page             INTEGER          NULL,
    heading          VARCHAR(300)     NULL,
    start_seconds    DOUBLE PRECISION NULL,
    end_seconds      DOUBLE PRECISION NULL,
    text             TEXT             NOT NULL,
    words            INTEGER          NOT NULL DEFAULT 0,
    embedding        BYTEA            NULL,   -- consider pgvector: vector(<dims>)
    embedding_model  VARCHAR(120)     NULL,
    created_at       TIMESTAMP(6)     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT pk_content_chunk PRIMARY KEY (id),
    CONSTRAINT ck_cc_kind CHECK (kind IN ('handbook', 'video', 'runbook'))
);

-- ---------------------------------------------------------------------
-- events
-- ---------------------------------------------------------------------
CREATE TABLE opshub.events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind            VARCHAR(20)   NOT NULL,
    user_id         BIGINT        NULL,
    user_role       BIGINT        NULL,
    action          VARCHAR(30)   NULL,
    module          VARCHAR(80)   NULL,
    record_type     VARCHAR(80)   NULL,
    record_id       BIGINT        NULL,
    project_id      BIGINT        NULL,
    content_type    VARCHAR(20)   NULL,
    content_id      BIGINT        NULL,
    outcome         VARCHAR(40)   NULL,
    old_values      TEXT          NULL,
    new_values      TEXT          NULL,
    description     TEXT          NULL,
    created_at      TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    target_user_id  BIGINT        NULL,
    severity        VARCHAR(20)   NULL,
    category        VARCHAR(40)   NULL,
    CONSTRAINT pk_events PRIMARY KEY (id),
    CONSTRAINT ck_events_kind CHECK (kind IN ('ASSISTANT', 'ACTIVITY', 'AUDIT')),
    CONSTRAINT ck_events_severity CHECK (severity IS NULL OR severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'INFO')),
    CONSTRAINT ck_events_category CHECK (category IS NULL OR category IN (
        'DATA_EXPORT', 'SYSTEM', 'SUPER_ADMIN', 'SETTINGS', 'NOTES', 'CONTENT',
        'AI_QUESTIONS', 'SECURITY', 'PERMISSIONS', 'PROJECT_MANAGEMENT',
        'USER_MANAGEMENT', 'AUTHENTICATION')),
    CONSTRAINT ck_events_old_json CHECK (old_values IS NULL OR old_values IS JSON),
    CONSTRAINT ck_events_new_json CHECK (new_values IS NULL OR new_values IS JSON)
);

-- ---------------------------------------------------------------------
-- notes
-- ---------------------------------------------------------------------
CREATE TABLE opshub.notes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind             VARCHAR(20)   NOT NULL,
    owner_id         BIGINT        NULL,
    project_id       BIGINT        NULL,
    source_note_id   BIGINT        NULL,
    entry_key        VARCHAR(80)   NULL,
    title            VARCHAR(300)  NOT NULL,
    content          TEXT          NULL,
    visibility_type  VARCHAR(24)   NULL,
    sort_order       INTEGER       NOT NULL DEFAULT 0,
    status           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by       BIGINT        NULL,
    created_by_role  BIGINT        NULL,
    CONSTRAINT pk_notes PRIMARY KEY (id),
    CONSTRAINT ck_notes_kind CHECK (kind IN ('FAQ', 'SHARED', 'PERSONAL')),
    CONSTRAINT ck_notes_owner CHECK (kind <> 'PERSONAL' OR owner_id IS NOT NULL),
    CONSTRAINT ck_notes_project CHECK (kind <> 'SHARED' OR project_id IS NOT NULL),
    CONSTRAINT ck_notes_visibility CHECK (visibility_type IS NULL OR visibility_type IN ('SELECTED_USERS', 'ALL_PROJECT_MEMBERS'))
);

-- ---------------------------------------------------------------------
-- note_attachments
-- ---------------------------------------------------------------------
CREATE TABLE opshub.note_attachments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    note_id          BIGINT        NOT NULL,
    file_name        VARCHAR(300)  NOT NULL,
    stored_name      VARCHAR(300)  NOT NULL,
    mime_type        VARCHAR(120)  NOT NULL,
    size_bytes       BIGINT        NOT NULL,
    -- NOTE: default 'FILE' is carried over from the source but violates ck_na_kind
    -- (same in SQL Server); inserts must always supply kind explicitly.
    kind             VARCHAR(20)   NOT NULL DEFAULT 'FILE',
    status           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at       TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by       BIGINT        NULL,
    created_by_role  BIGINT        NULL,
    CONSTRAINT pk_note_attachments PRIMARY KEY (id),
    CONSTRAINT ck_na_kind CHECK (kind IN ('doc', 'pdf', 'vid', 'img'))
);

-- ---------------------------------------------------------------------
-- note_recipients
-- ---------------------------------------------------------------------
CREATE TABLE opshub.note_recipients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    note_id     BIGINT        NOT NULL,
    user_id     BIGINT        NOT NULL,
    status      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT pk_note_recipients PRIMARY KEY (id),
    CONSTRAINT uq_note_recipient UNIQUE (note_id, user_id)
);

-- ---------------------------------------------------------------------
-- platform_config
-- ---------------------------------------------------------------------
CREATE TABLE opshub.platform_config (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kind                  VARCHAR(20)   NOT NULL,
    config_key            VARCHAR(120)  NOT NULL,
    route_path            VARCHAR(200)  NULL,
    default_title         VARCHAR(200)  NULL,
    title_override        VARCHAR(200)  NULL,
    module                VARCHAR(80)   NULL,
    icon                  VARCHAR(80)   NULL,
    nav_section           VARCHAR(80)   NULL,
    show_in_nav           BOOLEAN       NULL,
    is_active             BOOLEAN       NULL,
    autosave_enabled      BOOLEAN       NULL,
    autosave_interval_ms  INTEGER       NULL,
    required_permission   VARCHAR(150)  NULL,
    elements              TEXT          NULL,
    setting_value         TEXT          NULL,
    value_type            VARCHAR(20)   NULL,
    description           VARCHAR(300)  NULL,
    is_public             BOOLEAN       NULL,
    sort_order            INTEGER       NOT NULL DEFAULT 0,
    status                BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at            TIMESTAMP(6)  NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by            BIGINT        NULL,
    created_by_role       BIGINT        NULL,
    CONSTRAINT pk_platform_config PRIMARY KEY (id),
    CONSTRAINT uq_pc_kind_key UNIQUE (kind, config_key),
    CONSTRAINT ck_pc_kind CHECK (kind IN ('SETTING', 'PAGE')),
    CONSTRAINT ck_pc_elements_json CHECK (elements IS NULL OR elements IS JSON)
);

-- =====================================================================
-- Foreign keys (added after all tables exist)
-- =====================================================================
ALTER TABLE opshub.content          ADD CONSTRAINT fk_content_project FOREIGN KEY (project_id)     REFERENCES opshub.projects (id)      ON DELETE CASCADE;
ALTER TABLE opshub.content_chunk    ADD CONSTRAINT fk_cc_document     FOREIGN KEY (document_id)    REFERENCES opshub.content_index (id) ON DELETE CASCADE;
ALTER TABLE opshub.content_index    ADD CONSTRAINT fk_ci_content      FOREIGN KEY (content_id)     REFERENCES opshub.content (id)       ON DELETE CASCADE;
ALTER TABLE opshub.content_index    ADD CONSTRAINT fk_ci_project      FOREIGN KEY (project_id)     REFERENCES opshub.projects (id);
ALTER TABLE opshub.content_versions ADD CONSTRAINT fk_cv_content      FOREIGN KEY (content_id)     REFERENCES opshub.content (id)       ON DELETE CASCADE;
ALTER TABLE opshub.note_attachments ADD CONSTRAINT fk_na_note         FOREIGN KEY (note_id)        REFERENCES opshub.notes (id)         ON DELETE CASCADE;
ALTER TABLE opshub.note_recipients  ADD CONSTRAINT fk_nr_note         FOREIGN KEY (note_id)        REFERENCES opshub.notes (id)         ON DELETE CASCADE;
ALTER TABLE opshub.note_recipients  ADD CONSTRAINT fk_nr_user         FOREIGN KEY (user_id)        REFERENCES opshub.users (id);
ALTER TABLE opshub.notes            ADD CONSTRAINT fk_notes_owner     FOREIGN KEY (owner_id)       REFERENCES opshub.users (id);
ALTER TABLE opshub.notes            ADD CONSTRAINT fk_notes_project   FOREIGN KEY (project_id)     REFERENCES opshub.projects (id)      ON DELETE CASCADE;
ALTER TABLE opshub.notes            ADD CONSTRAINT fk_notes_source    FOREIGN KEY (source_note_id) REFERENCES opshub.notes (id);
ALTER TABLE opshub.project_access   ADD CONSTRAINT fk_pa_project      FOREIGN KEY (project_id)     REFERENCES opshub.projects (id)      ON DELETE CASCADE;
ALTER TABLE opshub.project_access   ADD CONSTRAINT fk_pa_user         FOREIGN KEY (user_id)        REFERENCES opshub.users (id);
ALTER TABLE opshub.users            ADD CONSTRAINT fk_users_role      FOREIGN KEY (role_id)        REFERENCES opshub.roles (id);

